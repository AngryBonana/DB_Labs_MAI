SELECT setval(pg_get_serial_sequence('faculties', 'faculty_id'), (SELECT MAX(faculty_id) FROM faculties));
SELECT setval(pg_get_serial_sequence('departments', 'department_id'), (SELECT MAX(department_id) FROM departments));
SELECT setval(pg_get_serial_sequence('groups', 'group_id'), (SELECT MAX(group_id) FROM groups));
SELECT setval(pg_get_serial_sequence('teachers', 'teacher_id'), (SELECT MAX(teacher_id) FROM teachers));
SELECT setval(pg_get_serial_sequence('teacher_departments', 'teacher_department_id'), (SELECT MAX(teacher_department_id) FROM teacher_departments));
SELECT setval(pg_get_serial_sequence('students', 'student_id'), (SELECT MAX(student_id) FROM students));
SELECT setval(pg_get_serial_sequence('courses', 'course_id'), (SELECT MAX(course_id) FROM courses));
SELECT setval(pg_get_serial_sequence('course_offerings', 'offering_id'), (SELECT MAX(offering_id) FROM course_offerings));

-- Контроль объёма данных (требование: >= 100 записей, >= 30 в одной таблице)
SELECT 'faculties' AS table_name, COUNT(*) AS row_count FROM faculties
UNION ALL SELECT 'departments', COUNT(*) FROM departments
UNION ALL SELECT 'groups', COUNT(*) FROM groups
UNION ALL SELECT 'teachers', COUNT(*) FROM teachers
UNION ALL SELECT 'teacher_departments', COUNT(*) FROM teacher_departments
UNION ALL SELECT 'students', COUNT(*) FROM students
UNION ALL SELECT 'courses', COUNT(*) FROM courses
UNION ALL SELECT 'course_offerings', COUNT(*) FROM course_offerings
UNION ALL SELECT 'grades', COUNT(*) FROM grades
UNION ALL SELECT 'ИТОГО',
 (SELECT COUNT(*) FROM faculties) + (SELECT COUNT(*) FROM departments) + (SELECT COUNT(*) FROM groups)
 + (SELECT COUNT(*) FROM teachers) + (SELECT COUNT(*) FROM teacher_departments) + (SELECT COUNT(*) FROM students)
 + (SELECT COUNT(*) FROM courses) + (SELECT COUNT(*) FROM course_offerings) + (SELECT COUNT(*) FROM grades);